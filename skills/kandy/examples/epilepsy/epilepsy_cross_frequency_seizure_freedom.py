# 11. Autonomous vector field.  No forcing, no nudging, no clipping.
# ---------------------------------------------------------------------------
def rhs(x, G):
    """dx_i/dt = (T_i(x_eff^i) - x_i)/tau_i.

    G[i, j] is the gain with which band i's equation sees band j:
        x_eff^i_j = BASE_j + G[i, j] * (x_j - BASE_j)
    G = 1 everywhere is the fitted model; G[i, j] = 0 lesions the j->i link.
    The DECAY term always uses the true x_i -- only the target is lesioned.
    """
    x = np.atleast_2d(x)
    out = np.empty_like(x)
    for b in range(NB):
        xe = BASE + G[b] * (x - BASE)
        xe[:, b] = x[:, b]          # a band always senses itself
        inner = models[b].predict(xe).ravel() * T_SCALE[b]
        out[:, b] = (from_inner_b(inner, b) - x[:, b]) / TAU[b]
    return out


def rollout(x0, steps, G, keep=True):
    """RK4.  T is squashed into the observed box and the dynamics contract
    toward it, so the trajectory cannot escape and nothing is clipped."""
    x = np.atleast_2d(np.asarray(x0, dtype=float)).copy()
    traj = np.empty((steps + 1, x.shape[0], NB)) if keep else None
    if keep:
        traj[0] = x
    smax = transition_score(x).copy()
    done = steps
    for s in range(steps):
        k1 = rhs(x, G)
        k2 = rhs(x + 0.5 * DT * k1, G)
        k3 = rhs(x + 0.5 * DT * k2, G)
        k4 = rhs(x + DT * k3, G)
        x = x + (DT / 6.0) * (k1 + 2 * k2 + 2 * k3 + k4)
        if not np.isfinite(x).all():
            done = s
            break
        smax = np.maximum(smax, transition_score(x))
        if keep:
            traj[s + 1] = x
    return {"traj": traj[:done + 1] if keep else None, "steps": done,
            "s_max": smax, "x_end": x}


