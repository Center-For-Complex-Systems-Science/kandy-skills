def knn_rate_r2(S, dt_s, lag_s, k=8, theiler_s=3.0):
    """R^2 of predicting the lag-increment from state-space neighbours that are
    far in TIME.  An upper bound on any autonomous vector field on this state."""
    L = max(1, int(round(lag_s / dt_s)))
    th = int(round(theiler_s / dt_s))
    Y = (S[L:] - S[:-L]) / lag_s
    Z = S[:len(Y)]
    n = len(Z)
    D = ((Z[:, None, :] - Z[None, :, :]) ** 2).sum(-1)
    D[np.abs(np.arange(n)[:, None] - np.arange(n)[None, :]) < th] = np.inf
    P = Y[np.argsort(D, axis=1)[:, :k]].mean(axis=1)
    return r2_per_output(Y, P)


def lorenz96_control(dim, n, dt_s, lag_s, F=8.0):
    """Deterministic chaotic reference at the SAME dimension and sample size.

    The estimator's own dimension penalty is large here; without matching it a
    5-D bound reads as 'the data is noise' when it partly means 'k-NN needs
    more points in 5-D'.  Lorenz-96 needs dim >= 4.
    """
    if dim < 4:
        return float("nan")
    burn = 2000

    def f(_t, y):
        return (np.roll(y, -1) - np.roll(y, 2)) * np.roll(y, 1) - y + F

    y0 = F * np.ones(dim)
    y0[0] += 0.01
    sol = solve_ivp(f, [0, (n + burn) * dt_s], y0,
                    t_eval=np.arange(n + burn) * dt_s, rtol=1e-10, atol=1e-12)
    Sc = sol.y.T[burn:]
    Sc = (Sc - Sc.mean(0)) / (Sc.std(0) + 1e-12)
    return float(np.nanmean(knn_rate_r2(Sc, dt_s, lag_s)))


