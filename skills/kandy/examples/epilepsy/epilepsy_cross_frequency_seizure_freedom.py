def causal_ewma(y: np.ndarray, tau_s: float) -> np.ndarray:
    """One-sided exponential smoother: output at t uses only samples <= t.

    A centred filter would leak future information into the state and make the
    increment partly self-predicting, which inflates every score downstream.
    """
    alpha = 1.0 - np.exp(-1.0 / (tau_s * FS))
    out = np.empty_like(y)
    acc = y[0].copy()
    for i in range(len(y)):
        acc = acc + alpha * (y[i] - acc)
        out[i] = acc
    return out


def build_state(tau_s: float):
    """Standardized channel-mean log amplitude per band, downsampled."""
    cols = [causal_ewma(LOG_ENV[name], tau_s).mean(axis=1) for name in BAND_NAMES]
    S = np.column_stack(cols)
    S = (S - S.mean(axis=0)) / (S.std(axis=0) + 1e-12)
    edge = int(round(EDGE_TRIM_SECONDS * FS))
    return S[edge:len(S) - edge:DS], T_RAW[edge:len(S) - edge:DS]


