for b, name in enumerate(BAND_NAMES):
    fpk, pk = _peakiness(STATE[:, b])
    null = [_peakiness(_ar1(STATE[:, b]))[1] for _ in range(40)]
    p95 = float(np.percentile(null, 95))
    real = bool(pk > p95)
    rhythm[name] = {"peak_hz": fpk, "peakiness": pk, "ar1_p95": p95,
                    "is_rhythm": real}
    print(f"         {name:>6}: peak {fpk:4.2f} Hz, peakiness x{pk:6.1f} vs "
          f"AR(1) p95 x{p95:6.1f}  -> "
          + ("RHYTHM" if real else "no rhythm beyond autocorrelation"), flush=True)
