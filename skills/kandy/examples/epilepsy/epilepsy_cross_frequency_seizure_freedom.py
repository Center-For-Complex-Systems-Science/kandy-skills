# ---------------------------------------------------------------------------
# 3b. Should an autonomous field REPRODUCE the envelope fluctuation, or is a
#     smooth trajectory the correct answer?
# ---------------------------------------------------------------------------
#
# The fitted rollout comes out smooth while the data wiggles, and that looks
# like a broken model until you ask whether the wiggle is reproducible at all.
# Two things have to be false for "the model should oscillate" to hold:
#
#   (a) the wiggle is a RHYTHM.  Tested against an AR(1) surrogate matched to
#       each band's own lag-1 autocorrelation -- no rhythm by construction.  If
#       the surrogate is just as "peaky", there is no oscillation to capture.
#       (A high-pass before this test manufactures a peak at its own corner, so
#       the test is run on the unfiltered envelope.)
#   (b) the wiggle is PREDICTABLE from the state -- the k-NN bound above.
#
# If both are false the fluctuation is stochastic, and the correct output of a
# deterministic autonomous field is the conditional mean, which is smooth.  A
# model that DID trace the wiggle would be memorizing noise.
#
from scipy.signal import welch                                   # noqa: E402

_rng_sur = np.random.default_rng(SEED)


def _peakiness(x):
    f, P = welch(x, 1.0 / DT, nperseg=min(256, len(x)))
    m = (f >= 0.2) & (f <= 5.0)
    return float(f[m][np.argmax(P[m])]), float(P[m].max() / np.median(P[m]))


def _ar1(x):
    r = float(np.corrcoef(x[:-1], x[1:])[0, 1])
    e = _rng_sur.normal(0, x.std() * np.sqrt(max(1 - r * r, 1e-6)), len(x))
    y = np.empty(len(x))
    y[0] = x[0]
    for i in range(1, len(x)):
        y[i] = r * y[i - 1] + e[i]
    return y


