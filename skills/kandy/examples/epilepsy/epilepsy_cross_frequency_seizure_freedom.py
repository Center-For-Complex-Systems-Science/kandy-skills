def fit_band(b, lift_fn_np, lift_fn_torch, dim, tag, rows_override=None):
    """Select lamb by BLOCKED k-fold CV over the given rows, then refit on them.

    Scoring on one window inside a basin selects the null model (see the
    docstring), so selection is always k-fold over the whole training span.
    """
    rws = train_rows if rows_override is None else rows_override
    splits = cv_splits if rows_override is None else make_cv_splits(rws)
    best, table = None, []
    for lamb in LAMB_GRID:
        fold = []
        for tr, te in splits:
            m = _new_model(b, lift_fn_np, lift_fn_torch, dim, tag)
            _fit_on(m, b, tr, lamb)
            fold.append(_rate_r2(m, b, te))
        score = float(np.mean(fold))
        table.append({"lamb": lamb, "cv_r2_rate": score,
                      "per_fold": [float(v) for v in fold]})
        if best is None or score > best[1]:
            best = (lamb, score)
    final = _new_model(b, lift_fn_np, lift_fn_torch, dim, tag)
    _fit_on(final, b, rws, best[0])
    return final, best[0], table


