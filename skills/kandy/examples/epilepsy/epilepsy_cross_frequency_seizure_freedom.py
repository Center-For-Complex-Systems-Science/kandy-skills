def lift_np(x):
    x = np.atleast_2d(x)
    feats = [np.ones(len(x))]
    feats += [x[:, b] for b in range(NB)]
    feats += [np.maximum(x[:, b] - THRESH[b], 0.0) for b in range(NB)]
    feats += [x[:, a] * x[:, b] for (a, b) in PAIRS]
    return np.column_stack(feats)


def lift_torch(x):
    feats = [torch.ones_like(x[:, 0])]
    feats += [x[:, b] for b in range(NB)]
    th = torch.as_tensor(THRESH, dtype=x.dtype)
    feats += [torch.clamp(x[:, b] - th[b], min=0.0) for b in range(NB)]
    feats += [x[:, a] * x[:, b] for (a, b) in PAIRS]
    return torch.stack(feats, dim=1)


def own_lift_np(b):
    """Own-band-only baseline lift for band b: the honest competitor."""
    def f(x):
        x = np.atleast_2d(x)
        return np.column_stack([np.ones(len(x)), x[:, b],
                                np.maximum(x[:, b] - THRESH[b], 0.0),
                                x[:, b] ** 2])
    return f


def own_lift_torch(b):
    def f(x):
        th = torch.as_tensor(THRESH[b], dtype=x.dtype)
        return torch.stack([torch.ones_like(x[:, b]), x[:, b],
                            torch.clamp(x[:, b] - th, min=0.0), x[:, b] ** 2], dim=1)
    return f


