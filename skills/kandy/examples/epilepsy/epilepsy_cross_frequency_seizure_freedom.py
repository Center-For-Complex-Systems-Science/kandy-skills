# ---------------------------------------------------------------------------
# PyKAN shim: curve2coef raises UnboundLocalError when its lstsq fails.
#
#     try:    coef = torch.linalg.lstsq(mat, y_eval).solution[:, :, :, 0]
#     except: print('lstsq failed')
#     return coef                      # <- coef was never assigned
#
# On small CV folds MKL rejects the call ("Parameter 6 was incorrect on entry
# to SGELSY") and the whole run dies partway through fitting -- nondeterminis-
# tically, since which folds trip it varies run to run.  PyKAN ships the right
# fallback for exactly this case, commented out directly beneath: a ridge
# pseudo-inverse.  This restores it, so a failed lstsq degrades to a slightly
# regularized solve instead of crashing.  Same precedent as the fit_sech2 shim
# in examples/_utils.py: reproduce the library's intent, do not silently
# diverge from it.
# ---------------------------------------------------------------------------
def _patch_curve2coef() -> int:
    """Replace curve2coef in EVERY kan.* module namespace that holds it.

    `from .spline import *` copies the function object into each importing
    module, so patching kan.spline alone leaves kan.KANLayer still calling the
    broken original.  Returns how many namespaces were patched.
    """
    import sys as _sys

    try:
        from kan import spline as _spline
    except ImportError:
        return 0

    _B_batch = _spline.B_batch

    def curve2coef(x_eval, y_eval, grid, k):
        batch, in_dim = x_eval.shape[0], x_eval.shape[1]
        out_dim = y_eval.shape[2]
        n_coef = grid.shape[1] - k - 1
        mat = _B_batch(x_eval, grid, k)
        mat = mat.permute(1, 0, 2)[:, None, :, :].expand(in_dim, out_dim, batch, n_coef)
        yy = y_eval.permute(1, 2, 0).unsqueeze(dim=3)
        try:
            return torch.linalg.lstsq(mat, yy).solution[:, :, :, 0]
        except Exception:                                       # noqa: BLE001
            lamb = 1e-8
            XtX = torch.einsum("ijmn,ijnp->ijmp", mat.permute(0, 1, 3, 2), mat)
            Xty = torch.einsum("ijmn,ijnp->ijmp", mat.permute(0, 1, 3, 2), yy)
            eye = torch.eye(XtX.shape[2], device=mat.device)[None, None]
            return torch.linalg.solve(XtX + lamb * eye, Xty)[:, :, :, 0]

    original = _spline.curve2coef
    n = 0
    for _name, _mod in list(_sys.modules.items()):
        if _name.split(".")[0] != "kan" or _mod is None:
            continue
        if getattr(_mod, "curve2coef", None) is original:
            _mod.curve2coef = curve2coef
            n += 1
    return n


CURVE2COEF_PATCHED = _patch_curve2coef()


