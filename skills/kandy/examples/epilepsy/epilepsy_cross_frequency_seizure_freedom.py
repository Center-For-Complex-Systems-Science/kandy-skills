# ---------------------------------------------------------------------------
# 12b. Is the fitted field actually BISTABLE?  This decides whether the
#      seizure-freedom question is even well posed on this fit.
# ---------------------------------------------------------------------------
#
# "Seizure freedom" presupposes a pre-ictal state the system can REMAIN in.
# If the fitted field has a single attractor -- the post-ictal one -- then every
# pre-ictal initial condition relaxes into the event no matter what is lesioned,
# and a lesion sweep can only change how FAST that happens, never whether it
# happens.  That is a property of the fit that has to be measured and reported,
# not left to be inferred from a flat sweep.
#
