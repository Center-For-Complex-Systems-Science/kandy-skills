# The control that decides whether the replay means anything.  T_i = c_i is a
# fitted SCALAR per band: no coupling, no gate, no state dependence at all.
# dx_i/dt = (c_i - x_i)/tau_i is a pure exponential from the pre-ictal level to
# the post-ictal one, which is already most of the shape of the observed
# transition.  If the full model does not beat this, "the model replays the
# seizure autonomously" is a statement about relaxation, not about mechanism.
C_CONST = T_TARGET[train_rows].mean(axis=0)


def rollout_const(x0, steps):
    x = np.atleast_2d(np.asarray(x0, dtype=float)).copy()
    traj = np.empty((steps + 1, x.shape[0], NB))
    traj[0] = x
    for st in range(steps):
        def f(y):
            return (C_CONST - y) / TAU
        k1, k2 = f(x), f(x + 0.5 * DT * f(x))
        k3 = f(x + 0.5 * DT * k2)
        k4 = f(x + DT * k3)
        x = x + (DT / 6.0) * (k1 + 2 * k2 + 2 * k3 + k4)
        traj[st + 1] = x
    return {"traj": traj, "steps": steps}


const = rollout_const(STATE[i0], N_STEPS)


def summarize(res, i=0):
    tr = res["traj"][:, i, :]
    s = transition_score(tr).ravel()
    base = s[:int(1.0 / DT)].mean()
    inside = np.all((tr >= STATE.min(0) - 0.1 * np.ptp(STATE, 0))
                    & (tr <= STATE.max(0) + 0.1 * np.ptp(STATE, 0)), axis=1)
    ref_tr = STATE[i0:i0 + len(tr)]
    rmse = float(np.sqrt(np.mean((tr[:len(ref_tr)] - ref_tr) ** 2)))
    # WHEN the rise happens, not just how big it is.  max-minus-baseline is
    # blind to timing: a slow sigmoid that drifts to the right endpoint over
    # 25 s scores the same "rise" as the real event, which completes in ~2 s.
    rise_v = float(s.max() - base)
    half = base + 0.5 * rise_v
    idx = np.argmax(s >= half) if np.any(s >= half) else len(s) - 1
    return {"rise": rise_v, "s_end": float(s[-1]),
            "t_half_s": float(T[i0] + idx * DT),
            "t_peak_s": float(T[i0] + int(np.argmax(s)) * DT),
            "complete": bool(res["steps"] == N_STEPS),
            "in_observed_range_frac": float(inside.mean()),
            "traj_rmse_vs_data": rmse,
            "seizes": bool(s.max() - base >= THRESH_S)}


