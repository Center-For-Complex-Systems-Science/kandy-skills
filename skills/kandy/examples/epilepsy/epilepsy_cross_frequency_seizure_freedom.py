# ---------------------------------------------------------------------------
# 10. Are there inter-frequency connections?  Circular-shift null.
# ---------------------------------------------------------------------------
#
# Selecting the best of 4 source bands per target inflates the apparent gain, so
# the null has to absorb that selection.  A circular shift of the SOURCE series
# preserves its marginal distribution and its autocorrelation and destroys only
# the cross-band timing, which is exactly the hypothesis under test.  Observed
# and null use the SAME ridge estimator on the SAME lift so the comparison is
# valid; the KAN number above is reported separately and not compared to this.
#
RIDGE = 1e-2


def ridge_cv_r2(design, target, tr, te):
    A = np.column_stack([design, np.ones(len(design))])
    G = A[tr].T @ A[tr] + RIDGE * np.eye(A.shape[1])
    w = np.linalg.solve(G, A[tr].T @ target[tr])
    return float(r2_per_output(target[te], A[te] @ w)[0])


def pair_design(target_b, src_b, x):
    """Columns of band src_b as they enter band target_b's equation."""
    cols = [x[:, src_b], np.maximum(x[:, src_b] - THRESH[src_b], 0.0)]
    if src_b != target_b:
        cols.append(x[:, src_b] * x[:, target_b])
    return np.column_stack(cols)


