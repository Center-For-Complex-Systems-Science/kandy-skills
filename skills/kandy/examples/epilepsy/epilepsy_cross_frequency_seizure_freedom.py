def r2_per_output(y: np.ndarray, p: np.ndarray) -> np.ndarray:
    y = np.atleast_2d(y.T).T
    p = np.atleast_2d(p.T).T
    den = np.sum((y - y.mean(axis=0)) ** 2, axis=0)
    den = np.where(den > 0, den, np.nan)
    return 1.0 - np.sum((y - p) ** 2, axis=0) / den


