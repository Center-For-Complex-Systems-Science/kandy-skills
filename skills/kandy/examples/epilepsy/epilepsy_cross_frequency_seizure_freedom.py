# ---------------------------------------------------------------------------
# 12c. What timescales can the fitted field actually produce?
# ---------------------------------------------------------------------------
#
# Separates "smooth because the fluctuation is noise" (correct) from "smooth
# because the field is too slow to have an event" (a real defect).  The
# observed transition completes in a couple of seconds; if every eigenvalue of
# the linearized field is slower than that, the model cannot produce the onset
# shape no matter what is lesioned.
#
def _jacobian(x0, eps=1e-4):
    J = np.zeros((NB, NB))
    for j in range(NB):
        xp, xm = x0.copy(), x0.copy()
        xp[j] += eps
        xm[j] -= eps
        J[:, j] = (rhs(xp, G_ONE)[0] - rhs(xm, G_ONE)[0]) / (2 * eps)
    return J


J_att = _jacobian(reps[0] if reps else STATE[i0])
ev = np.linalg.eigvals(J_att)
timescales = sorted(1.0 / np.abs(ev.real), reverse=True)
osc = [2 * np.pi / abs(e.imag) for e in ev if abs(e.imag) > 1e-9]
print(f"\n[SPECTRUM] linearized at the attractor: timescales "
      + ", ".join(f"{v:.1f}s" for v in timescales), flush=True)
print(f"[SPECTRUM] oscillatory modes: "
      + (", ".join(f"period {v:.0f}s" for v in sorted(set(np.round(osc, 1))))
         if osc else "none (pure relaxation)"), flush=True)
print(f"[SPECTRUM] fastest timescale {min(timescales):.1f}s vs an observed "
      f"transition of ~2s -> the field is "
      + ("fast enough to produce the onset" if min(timescales) <= 3.0 else
         "TOO SLOW to produce the onset shape; this is a real defect, distinct "
         "from the (correct) absence of envelope wiggle"), flush=True)


