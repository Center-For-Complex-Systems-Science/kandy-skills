#!/usr/bin/env python3
"""Cross-frequency band-amplitude dynamics: autonomous seizure replay, and
seizure freedom by lesioning the connections BETWEEN frequency bands.

The question
------------
Is the seizure in ``Dory_2021_04_12_006`` generated by interactions BETWEEN
frequency bands, and if so, can cutting specific band-to-band connections
abolish it -- in a model that runs with no external drive at all?

Three things have to be true for that question to be answerable, and each is
tested here before the answer is reported:

1. there are inter-frequency connections (band j's level informs band i's
   rate, beyond band i's own state, above a circular-shift null);
2. the fitted field replays the event AUTONOMOUSLY (no forcing term, no
   nudging toward the measurement, no clipping);
3. cutting cross-band connections changes the outcome.

Why band AMPLITUDES and not phases
----------------------------------
Every previous model in this directory is built on phase.  They all fail for
the same structural reason, recorded in ``epilepsy_adaptive_kuramoto_fit.py``
and measured again by ``epilepsy_adaptive_kuramoto_seizure_freedom.py``: the
per-channel mean phase velocity in this recording drifts 2-5x across the
seizure, so a fixed-omega oscillator is wrong in its constant term alone.  The
seizure-freedom script promotes omega to a state and STILL lands with the
coupling term regularized to a ratio of 2.2e-3 against omega, a held-out
coupling gain of 8.6e-6, and an autonomous mean-omega rise of +5.5 rad/s
against an observed +57.1.  Its own report calls that mode "induction": the
fitted model does not seize, so the seizure-freedom question is vacuous on it.

The amplitude state does not have that problem, and the reason is visible in
the raw spectra.  Ictal/pre-ictal band power (hippocampus_R): delta 0.49,
theta 8.8, alpha 17.4, beta 31.5, gamma 16.0.  Delta goes DOWN while every
faster band goes UP.  The event is a redistribution of power ACROSS bands,
which is exactly a cross-frequency observable, and it is a state transition
rather than a pulse: 15+ s after onset, alpha is still 47x its pre-ictal
level.  Standardized band amplitudes averaged over channels give

    pre-ictal   (+0.24, -1.12, -1.21, -1.31, -1.27)
    post-ictal  (-0.06, +0.84, +0.44, +0.36, +0.35)

with ~13 s dwell in the first and ~22 s in the second.  Two long-occupied
regions of state space with one crossing between them is what a BISTABLE
autonomous vector field looks like, and unlike a single transient it gives a
fit something to constrain the field with in both basins.

Model
-----
State x in R^5, one standardized log-amplitude envelope per band.  Each band
relaxes toward a target that depends on the whole band vector:

    dx_i/dt = (T_i(x) - x_i) / tau_i,     T_i squashed into the observed box

Fixed points are exactly T(x) = x, so bistability is T crossing the diagonal
three times, and the cross-frequency coupling lives entirely inside T.  The
form is also what makes the model safe to integrate: T is bounded and the
dynamics contract toward it, so no rollout can run away and NOTHING is
clipped anywhere in this script.

The lift for each T_i carries, with every column attributable to a band:

    1                       constant
    x_b            (5)      linear cross-band
    ReLU(x_b - th_b) (5)    gated cross-band -- the bistability mechanism
    x_b * x_c      (10)     multiplicative cross-frequency coupling

KANDy is A*Psi(phi(x)) with Psi separable, so the cross-band terms have to be
written into the lift explicitly; a KAN cannot manufacture x_b*x_c from
separate x_b and x_c edges.  That is the whole reason this lift is spelled out
rather than handed a raw state.

The lesion
----------
"Disrupting the connection between bands" is implemented as a LESION, not a
coefficient deletion: in band i's equation, band j is clamped to its pre-ictal
baseline,

    x_j as seen by i  =  x_j^base + g_ij * (x_j - x_j^base)

so g_ij = 0 means band i can no longer sense band j's excursion, while every
spline is still evaluated at a value the recording actually visited.  Deleting
a coefficient instead would push the remaining edges off their fitted support.
g_ij = 1 is the fitted model; the sweep runs g in [0, 2] to get both the
abolition boundary and the potentiation direction.

What is measured before anything is claimed
-------------------------------------------
* A model-free determinism ceiling on this state, with a DIMENSION-MATCHED
  Lorenz-96 control.  A 2-D van der Pol control is not a valid reference for a
  5-D k-NN bound -- measured here, the same estimator that scores 0.999 on 2-D
  van der Pol scores only ~0.43 on 6-D Lorenz-96 at this sample size, so an
  unmatched control makes the data look far worse than it is.
* Held-out skill against the two baselines that actually threaten each claim:
  zero-change (persistence) and an own-band-only model.  A cross-frequency
  claim is worth nothing next to the own-band model unless it beats it.
* A circular-shift null for the cross-band gain.  Picking the best of 4
  candidate source bands per target inflates the apparent gain; shifting the
  source series destroys cross-band timing while preserving each band's own
  distribution and autocorrelation, so the null absorbs exactly that bias.
* An initial-condition specificity scan, so "the model seizes" cannot be
  satisfied by a trajectory that would have gone there from anywhere.
* A CONSTANT-TARGET relaxation baseline for the replay.  dx_i/dt =
  (c_i - x_i)/tau_i with c_i a fitted scalar has no coupling of any kind, yet
  it produces a monotone rise from the pre-ictal level to the post-ictal one
  -- which is most of what the observed transition looks like.  Any claim that
  the replay demonstrates a mechanism has to beat that, and the gate below is
  written so it cannot pass without doing so.

Where the evidence actually lives, and the two model sets
---------------------------------------------------------
Inside either basin dx/dt is ~0 and is mostly noise, so a held-out block drawn
from a basin asks the model to predict nothing and every method scores near or
below zero there.  That block tests the model's description of an attractor.
It cannot answer the question this script is about, which is whether
cross-frequency coupling drives the EVENT -- and the event is the transition.

So two model sets are fitted, and they are never mixed:

  SET A -- trained with the transition IN the training rows.  A bistable field
           cannot be identified at all from basins alone, so this is the set
           used for the rollout, the replay and the lesion sweep.  Its held-out
           blocks are the two basin blocks, and they score the attractors.
  SET B -- trained with the transition WITHHELD.  Used only to score skill ON
           the transition.  This is the honest generalization number and the
           one the cross-frequency claim rests on: can a model that never saw
           the seizure predict its band dynamics, and does it need cross-band
           terms to do it?

The circular-shift null is scored on the transition fold for the same reason.

One caveat stated precisely rather than glossed: two SCALARS per band, tau_i
and the target scale, are selected on SET A rows and reused by SET B, so SET B
is not hermetically sealed from the transition.  They carry a timescale and a
magnitude, not a shape, and -- decisively for the conclusion -- the cross-band
model, the own-band model and the persistence baseline all share the very same
two scalars.  A leak common to every arm cannot manufacture a difference
between them, and every claim below is a difference between arms.

A validation-design trap this script had to fix
-----------------------------------------------
The first version selected lamb and tau on a single 12-17 s block.  That block
sits inside the post-ictal plateau, where dx/dt ~ 0, so the best-scoring model
on it is the one that predicts nothing: lamb = 1.0 (the maximum on the grid)
was selected for alpha, beta and gamma, their KANs collapsed to constants, and
the lesion sweep was flat -- not because the bands are uncoupled but because
there was nothing left in the model to lesion.  The tau scan showed the same
thing by hitting the top of its grid.  Hyperparameters are now chosen by
BLOCKED K-FOLD CV over the whole non-test record, so every selection is scored
on folds that contain the transition and both basins.  The two test blocks are
never touched by selection.

Honest limits, stated before the results rather than after
----------------------------------------------------------
There is ONE seizure in this recording.  Both basins are well sampled, but the
CROSSING is observed once, so the separatrix location and the mechanism of
crossing are identified by a single trajectory and are extrapolation in a way
the two basins are not.  Both held-out blocks necessarily sit inside a basin
(a transition cannot be held out when there is only one), so the held-out
numbers score the model's description of the attractors, not of the crossing.
Every g_ij is a coefficient of a fitted model, not a clinical intervention.

Run:
    cd skills/kandy/examples && python epilepsy/epilepsy_cross_frequency_seizure_freedom.py
"""

